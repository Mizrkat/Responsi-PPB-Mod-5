-- ============================================================================
-- SUPABASE DATABASE SCHEMA & STORAGE BUCKET: KAYU & RUANG FURNITURE PWA
-- Mencakup 4 Tabel Utama + Storage Bucket:
--   1. public.furnitures (Katalog & CRUD Produk Furniture)
--   2. public.profiles   (Informasi Profil Akun Praktikan: Nama, NIM, Kelompok, Avatar)
--   3. public.favorites  (Daftar Produk Favorit / Wishlist Pengguna)
--   4. public.reviews    (Ulasan & Rating Bintang Pelanggan)
--   5. storage.buckets   (Bucket "furnitures" & "avatars" untuk Simpan File Upload)
--
-- Cara Pakai: Salin seluruh script SQL ini ke menu "SQL Editor" di Dashboard
--             Supabase Anda, lalu klik tombol "Run".
-- ============================================================================

-- 1. Fungsi Trigger Otomatis untuk Kolom updated_at
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ============================================================================
-- 2. TABEL 1: public.furnitures (Katalog & CRUD Produk Furniture)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.furnitures (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'Kursi',
  material TEXT NOT NULL DEFAULT 'Kayu Jati Solid',
  assembly_type TEXT DEFAULT 'Siap Pakai (Fully Assembled)',
  price NUMERIC NOT NULL DEFAULT 0,
  description TEXT DEFAULT '',
  specs JSONB DEFAULT '[]'::jsonb,
  steps TEXT[] DEFAULT '{}',
  image_url TEXT DEFAULT '/furniture/chair.jpg',
  is_featured BOOLEAN DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

DROP TRIGGER IF EXISTS trg_furnitures_updated_at ON public.furnitures;
CREATE TRIGGER trg_furnitures_updated_at
BEFORE UPDATE ON public.furnitures
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();

-- ============================================================================
-- 3. TABEL 2: public.profiles (Informasi Profil Akun Praktikan)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL UNIQUE,
  username TEXT NOT NULL DEFAULT 'Mahasiswa Praktikan PPB',
  nim TEXT NOT NULL DEFAULT '21120123140001',
  kelompok TEXT NOT NULL DEFAULT 'Kelompok 05 — Praktikum PPB',
  prodi TEXT DEFAULT 'Teknik Komputer — Universitas Diponegoro',
  bio TEXT DEFAULT 'Pengembang Aplikasi Progressive Web App (PWA) Toko Furniture Kayu & Ruang.',
  avatar_url TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

DROP TRIGGER IF EXISTS trg_profiles_updated_at ON public.profiles;
CREATE TRIGGER trg_profiles_updated_at
BEFORE UPDATE ON public.profiles
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();

-- ============================================================================
-- 4. TABEL 3: public.favorites (Daftar Favorit / Wishlist Pengguna)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.favorites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  furniture_id BIGINT NOT NULL REFERENCES public.furnitures(id) ON DELETE CASCADE,
  user_id UUID NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(furniture_id, user_id)
);

-- ============================================================================
-- 5. TABEL 4: public.reviews (Ulasan & Rating Pelanggan)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  furniture_id BIGINT NOT NULL REFERENCES public.furnitures(id) ON DELETE CASCADE,
  user_id UUID,
  user_name TEXT NOT NULL DEFAULT 'Pelanggan Kayu & Ruang',
  rating INTEGER NOT NULL CHECK (rating >= 1 AND rating <= 5),
  comment TEXT DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================================
-- 6. INDEKS PENCARIAN & PERFORMA QUERY
-- ============================================================================
CREATE INDEX IF NOT EXISTS idx_furnitures_category ON public.furnitures(category);
CREATE INDEX IF NOT EXISTS idx_profiles_user_id ON public.profiles(user_id);
CREATE INDEX IF NOT EXISTS idx_favorites_user_id ON public.favorites(user_id);
CREATE INDEX IF NOT EXISTS idx_reviews_furniture_id ON public.reviews(furniture_id);

